import fs from 'fs-extra';
import path from 'path';
import type { KigumiConfig } from './config.js';

/**
 * Regenerate the Web Awesome setup file with updated theme configuration
 *
 * This function is used by init and all theme management commands
 * to ensure webawesome.ts is always in sync with the config.
 */
export async function regenerateWebAwesomeSetup(
  cwd: string,
  config: KigumiConfig,
  utilsDir: string
): Promise<void> {
  const tier = config.webAwesome?.tier || 'free';
  const packageName = tier === 'pro'
    ? '@awesome.me/webawesome-pro'
    : '@awesome.me/webawesome';

  // Determine CSS import path
  let themeImport = '';
  if (config.theme.selected !== 'none') {
    const themeName = config.theme.selected;
    themeImport = `import '${packageName}/dist/styles/themes/${themeName}.css';`;
  }

  // User overrides import
  const userOverridesImport = `import '@/styles/theme.css';`;

  // Generate runtime script to set HTML classes
  const themeClasses = config.theme.selected !== 'none'
    ? `
// Apply theme classes to <html> element
if (typeof document !== 'undefined') {
  const html = document.documentElement;

  // Remove old theme classes (for hot reload)
  html.className = html.className
    .replace(/\\bwa-theme-\\S+/g, '')
    .replace(/\\bwa-palette-\\S+/g, '')
    .replace(/\\bwa-brand-\\S+/g, '');

  // Add new theme classes
  html.classList.add('wa-theme-${config.theme.selected}');
  html.classList.add('wa-palette-${config.theme.palette}');
  html.classList.add('wa-brand-${config.theme.brandColor}');
}
`
    : '';

  const setupFileContent = `/**
 * Web Awesome Setup
 *
 * This file is auto-generated by Kigumi CLI.
 * It imports the selected theme and applies theme classes to the <html> element.
 *
 * Current theme: ${config.theme.selected}
 * Current palette: ${config.theme.palette}
 * Current brand: ${config.theme.brandColor}
 *
 * To change themes, use: kigumi theme set <name>
 * To change brand color, use: kigumi brand set <color>
 */

${themeImport}

${userOverridesImport}
${themeClasses}
export {};
`;

  const setupFilePath = path.join(cwd, utilsDir, 'webawesome.ts');
  await fs.writeFile(setupFilePath, setupFileContent);
}
