/**
 * overrides.css and its layer (issue #194, docs/adr/0009).
 *
 * The file is the user's, like theme.css: created when missing, never
 * overwritten. A layers.css written before the overrides layer existed gets
 * the layer added in place, keeping everything else in it.
 */

import { describe, it, expect, beforeEach, afterEach } from 'vitest';
import fs from 'fs-extra';
import path from 'path';
import os from 'os';

import { ensureOverridesLayer } from '../../src/utils/overrides-css.js';

const STYLES_DIR = 'src/styles';

let cwd: string;

beforeEach(async () => {
  cwd = await fs.mkdtemp(path.join(os.tmpdir(), 'kigumi-overrides-'));
  await fs.ensureDir(path.join(cwd, STYLES_DIR));
});

afterEach(async () => {
  await fs.remove(cwd);
});

function stylesFile(name: string): string {
  return path.join(cwd, STYLES_DIR, name);
}

describe('ensureOverridesLayer: overrides.css', () => {
  it('creates an overrides.css that holds no rule', async () => {
    const result = await ensureOverridesLayer(cwd, STYLES_DIR);

    expect(result.created).toBe(true);
    const content = await fs.readFile(stylesFile('overrides.css'), 'utf-8');
    expect(content).toContain('overrides');
    // Comments only: a fresh file changes nothing on the page.
    expect(content.replace(/\/\*[\s\S]*?\*\//g, '').trim()).toBe('');
  });
});

describe('ensureOverridesLayer: an existing overrides.css', () => {
  it('leaves it byte for byte', async () => {
    // Not the format the CLI writes: CRLF, no trailing newline, a real rule.
    const mine = '.Card {\r\n  border: 2px solid red;\r\n}';
    await fs.writeFile(stylesFile('overrides.css'), mine);

    const result = await ensureOverridesLayer(cwd, STYLES_DIR);

    expect(result.created).toBe(false);
    expect(await fs.readFile(stylesFile('overrides.css'), 'utf-8')).toBe(mine);
  });
});

/** layers.css as the CLI wrote it before the overrides layer. */
function layersBeforeOverrides(qualified: boolean): string {
  const base = qualified ? ' layer(base)' : '';
  const theme = qualified ? ' layer(theme)' : '';
  return `/**
 * Web Awesome CSS Cascade Layers
 *
 * This file is auto-generated by Kigumi CLI.
 * It wraps Web Awesome CSS in cascade layers for predictable specificity control.
 *
 * Layer hierarchy (earlier = lower priority):
 * 1. base - Web Awesome foundation + theme styles
 * 2. theme - Your custom CSS overrides (theme.css)
 *
 * Learn more: https://developer.mozilla.org/en-US/docs/Web/CSS/@layer
 */

/* Define layer order, a theme without overrides of its own */
@layer base, theme;

/* Layer 1: Web Awesome base styles */
@import '@awesome.me/webawesome/dist/styles/webawesome.css'${base};

/* Layer 1: Web Awesome theme styles */
@import '@awesome.me/webawesome/dist/styles/themes/default.css'${base};

/* Layer 2: Your custom CSS overrides (sibling of layers.css) */
@import './theme.css'${theme};

/* The user's own addition, kept as it is */
@import './print.css' layer(theme);
`;
}

describe('ensureOverridesLayer: a layers.css without the overrides layer', () => {
  it('adds the layer and imports overrides.css right after theme.css', async () => {
    await fs.writeFile(stylesFile('layers.css'), layersBeforeOverrides(true));

    const result = await ensureOverridesLayer(cwd, STYLES_DIR);

    expect(result.layers).toBe('added');
    const content = await fs.readFile(stylesFile('layers.css'), 'utf-8');
    expect(content).toContain('@layer base, theme, overrides;');
    const theme = content.indexOf("@import './theme.css' layer(theme);");
    const overrides = content.indexOf(
      "@import './overrides.css' layer(overrides);"
    );
    expect(overrides).toBeGreaterThan(theme);
    expect(overrides).toBeLessThan(content.indexOf("@import './print.css'"));
    // Nothing else changes: drop what was added and the original is back.
    const added = content
      .replace(', overrides;', ';')
      .replace(
        /\n\n\/\* Layer 3:[^\n]*\n@import '\.\/overrides\.css'[^\n]*/,
        ''
      );
    expect(added).toBe(layersBeforeOverrides(true));
  });

  it('imports overrides.css without a qualifier where theme.css has none', async () => {
    // Pages Router: unlayered, so overrides.css wins by coming later.
    await fs.writeFile(stylesFile('layers.css'), layersBeforeOverrides(false));

    await ensureOverridesLayer(cwd, STYLES_DIR);

    const content = await fs.readFile(stylesFile('layers.css'), 'utf-8');
    expect(content).toContain("@import './overrides.css';");
    expect(content).not.toContain('layer(overrides)');
  });

  it('follows a theme.css import written with the project alias', async () => {
    // Older CLI versions imported theme.css as '@/styles/theme.css'.
    await fs.writeFile(
      stylesFile('layers.css'),
      "@layer base, theme;\n@import '@/styles/theme.css' layer(theme);\n"
    );

    const result = await ensureOverridesLayer(cwd, STYLES_DIR);

    expect(result.layers).toBe('added');
    const content = await fs.readFile(stylesFile('layers.css'), 'utf-8');
    expect(content).toContain(
      "@import '@/styles/overrides.css' layer(overrides);"
    );
  });

  it('counts an aliased overrides.css import as present', async () => {
    const current = `@layer base, theme, overrides;\n@import '@/styles/theme.css' layer(theme);\n@import '@/styles/overrides.css' layer(overrides);\n`;
    await fs.writeFile(stylesFile('layers.css'), current);

    const result = await ensureOverridesLayer(cwd, STYLES_DIR);

    expect(result.layers).toBe('present');
    expect(await fs.readFile(stylesFile('layers.css'), 'utf-8')).toBe(current);
  });

  it('leaves a layers.css that already imports overrides.css as it is', async () => {
    const current = `@layer base, theme, overrides;\n@import './theme.css' layer(theme);\n@import './overrides.css' layer(overrides);\n`;
    await fs.writeFile(stylesFile('layers.css'), current);

    const result = await ensureOverridesLayer(cwd, STYLES_DIR);

    expect(result.layers).toBe('present');
    expect(await fs.readFile(stylesFile('layers.css'), 'utf-8')).toBe(current);
  });

  it('reports a layers.css without a theme.css import and leaves it alone', async () => {
    const restructured = `@import './everything.css';\n`;
    await fs.writeFile(stylesFile('layers.css'), restructured);

    const result = await ensureOverridesLayer(cwd, STYLES_DIR);

    expect(result.layers).toBe('unrecognized');
    expect(await fs.readFile(stylesFile('layers.css'), 'utf-8')).toBe(
      restructured
    );
    // The file still lands, ready for the import the user adds by hand.
    expect(result.created).toBe(true);
  });

  it('reports no layers.css when there is none', async () => {
    const result = await ensureOverridesLayer(cwd, STYLES_DIR);

    expect(result.layers).toBe('absent');
    expect(await fs.pathExists(stylesFile('layers.css'))).toBe(false);
  });
});
